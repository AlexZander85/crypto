def update_html_terms(fpath):
    target_path = os.path.normpath(fpath)
    print(f"Updating TERMS_RAW in {os.path.basename(target_path)}...")
    with open(target_path, 'r', encoding='utf-8') as f:
        html = f.read()

    # Clean CATS
    cats_def = "const CATS = { basics: ['Основы', '#22c55e'], trading: ['Торговля', '#38bdf8'], metrics: ['Метрики', '#a78bfa'], algo: ['Алго-модели', '#fb923c'], risk: ['Риск-менеджмент', '#f43f5e'], ru: ['Право РФ', '#f472b6'], infra: ['Инфраструктура', '#eab308'], psy: ['Психология', '#ec4899'] };"
    html = re.sub(r'const CATS = \{.*?\};', cats_def, html, flags=re.DOTALL)

    # Format JSON
    terms_json_str = json.dumps(existing_terms_list, ensure_ascii=False, indent=2)
    terms_raw_def = f"const TERMS_RAW = {terms_json_str};\nconst TERMS = TERMS_RAW.filter(Boolean);"

    # Replace TERMS_RAW block using exact slice replacement
    s_idx = html.find('const TERMS_RAW = [')
    e_idx = html.find('const TERMS = TERMS_RAW.filter(Boolean);', s_idx)
    if s_idx != -1 and e_idx != -1:
        end_of_statement = e_idx + len('const TERMS = TERMS_RAW.filter(Boolean);')
        html = html[:s_idx] + terms_raw_def + html[end_of_statement:]

    # Smart openTermByName
    new_open_term_fn = """function openTermByName(name){
  if(!name) return;
  var q = name.toLowerCase().trim();
  var idx = TERMS.findIndex(x => x.t.toLowerCase() === q || x.t.toLowerCase().startsWith(q) || q.startsWith(x.t.toLowerCase()));
  if(idx === -1) idx = TERMS.findIndex(x => x.t.toLowerCase().includes(q) || q.includes(x.t.toLowerCase()));
  if(idx === -1){
    var words = q.split(/[\\s\\(\\)\\[\\],:—\\-]+/).filter(w => w.length >= 4);
    for(var i = 0; i < words.length; i++){
      var w = words[i];
      idx = TERMS.findIndex(x => x.t.toLowerCase().includes(w));
      if(idx !== -1) break;
    }
  }
  if(idx !== -1) openTermModal(idx);
}"""

    # Replace openTermByName function
    fn_start = html.find('function openTermByName(name){')
    if fn_start != -1:
        fn_end = html.find('function closeTermModal(e){', fn_start)
        if fn_end != -1:
            html = html[:fn_start] + new_open_term_fn + '\n\n' + html[fn_end:]

    with open(target_path, 'w', encoding='utf-8') as f:
        f.write(html)
    print(f"Successfully updated TERMS_RAW in {os.path.basename(target_path)}")

